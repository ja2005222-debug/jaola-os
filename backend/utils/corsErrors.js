/**
 * 🚦 يميّز رفض CORS المتعمَّد عن أي خطأ خادم حقيقي آخر.
 *
 * ⚠️ درسٌ حيّ (٢٦ أغسطس ٢٠٢٦): رفض `cors()` لأصلٍ غير مسموح يصل لمعالج
 * الأخطاء العام كخطأ عادي، فكان يُردّ عليه بـ500 مطابقاً لأي عطب داخلي.
 * حين نُسي تحديث `ALLOWED_ORIGINS` بعد ربط نطاقٍ مخصّص (`www.jaola.dev`)،
 * صار الموقع **يرفض طلبات نفسه من نفسه**: كل `<script type="module">`
 * يرسل ترويسة `Origin` معيارياً، فيفحصها الخادم ويرمي، فتسقط في 500 عام
 * بدل رفضٍ صريح بـ403 يوضّح أن القرار أمنيٌّ متعمَّد لا عطباً — وسجلّات
 * الإنتاج كانت تعرض «Server Error» لكل طلب، لا تصنيفاً يقود لسبب حقيقي
 * (متغيّر بيئة ناقص) بسرعة.
 */
export function isCorsRejection(err) {
    return typeof err?.message === 'string' && err.message.startsWith('CORS: Origin غير مسموح');
}
