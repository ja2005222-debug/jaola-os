/**
 * 🧭 تمييز «مسار ملف» عن «مسار صفحة» في احتياط توجيه SPA.
 *
 * ⚠️ درس إنتاجي (٢٥ أغسطس ٢٠٢٦) — بلاغ «jaola.dev يعطي صفحة بيضاء فقط»:
 * كان الاحتياط يردّ index.html على **كل** مسار غير معروف، بما فيه الأصول
 * المفقودة. تبويبٌ مفتوح منذ ما قبل النشر يطلب `/assets/index-<hash>.js`
 * لم يعد موجوداً، فيتلقّى HTML بترويسة `text/html` مكان وحدة جافاسكربت؛
 * يرفض المتصفح تنفيذه، وتفشل حزمة الصفحة، وتُفرَّغ شجرة React → بياض تام
 * مع بقاء عنوان التبويب (فهو من index.html الثابت).
 *
 * 404 صريحة أصدق: تصل للواجهة كـ`vite:preloadError` فتُعاد التحميل مرة
 * واحدة تلقائياً (frontend/src/chunkReload.js) وتُجلب أسماء الحزم الصحيحة.
 *
 * القاعدة: مسارات الصفحات بلا امتداد (/dashboard، /billing، /privacy…)،
 * والأصول إما تحت `/assets/` أو منتهية بامتداد ملف قصير.
 */
export function isStaticAssetPath(pathname) {
    return pathname.startsWith('/assets/') || /\.[a-z0-9]{2,5}$/i.test(pathname);
}
