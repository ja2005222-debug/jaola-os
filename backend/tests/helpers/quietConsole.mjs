const KEYS = ['log', 'warn', 'error', 'info', 'debug'];

export function quietConsole() {
    const real = {};
    const lines = [];
    for (const k of KEYS) {
        real[k] = console[k];
        console[k] = (...args) => { lines.push(args.map(String).join(' ')); };
    }
    return {
        lines,
        restore() { for (const k of KEYS) console[k] = real[k]; },
    };
}
