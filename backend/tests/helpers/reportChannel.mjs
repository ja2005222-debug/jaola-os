const DIVERTED = ['log', 'info', 'debug'];   // warn/error على stderr أصلاً

export function divertConsoleToStderr() {
    for (const key of DIVERTED) {
        console[key] = (...args) => {
            process.stderr.write(`${args.map(String).join(' ')}\n`);
        };
    }
}
