// 🚫 الجملةُ التي تنفي هي التي تُوجِب.
//
// مقيسٌ من أوّل بناءٍ حرٍّ حيّ (`from0`). كُتب في المواصفة حرفيّاً:
//
//     «تعمل بالكامل داخل المتصفّح **بلا خادم ولا حساب**»
//
// فبَنَتْ جولا Next.js + API + Prisma (١٦ ملفّاً). والسببُ أنّ `needsBackend` تُطابق
// كلماتٍ مفردةً ولا ترى النفيَ إطلاقاً، فالتقطت «**حساب**» من «بلا **حساب**» —
// الجملةُ التي تنفي الحسابَ هي التي أوجبته. ومعها «تسجيل» من «**تسجيل** ما حُفظ»
// (تسجيلُ حفظٍ لا تسجيلُ دخول)، و«بيانات» من «بقاء البيانات».
//
// وأثرُه ليس تجميليّاً: مشروعٌ قال صاحبُه إنّه بلا خادم يخرج بـPrisma وقاعدةِ بيانات
// ومسارات API لا تعمل حيث يُنشَر — وهو عينُ العطب الذي وُجدت `backendNeed.js` لأجله.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { needsBackend, needsRelationalDb } from '../agents/backendNeed.js';
import { divertConsoleToStderr } from './helpers/reportChannel.mjs';

divertConsoleToStderr();

test('🔴 «بلا حساب» لا تُوجب حساباً — والنفيُ لا يُقرأ إثباتاً', () => {
    assert.equal(needsBackend('أداةٌ تعمل داخل المتصفّح بلا خادم ولا حساب'), false,
        'الجملةُ التي تنفي الخادمَ هي التي أوجبته');
});

test('🔴 وكلُّ صيغِ النفي المتداولة — لا «بلا» وحدَها', () => {
    for (const g of [
        'أداةٌ بدون تسجيل دخول',
        'أداةٌ دون قاعدة بيانات',
        'a tool with no login',
        'a tool without a database',
    ]) assert.equal(needsBackend(g), false, `لم يُقرأ النفيُ في: «${g}»`);
});

test('🔴 والإثباتُ يبقى إثباتاً — لا تُعطَّل البوّابةُ بحجّة النفي', () => {
    for (const g of [
        'موقعٌ فيه تسجيل دخول ولوحة تحكم',
        'متجرٌ بسلة شراء ودفع',
        'a site with login and a dashboard',
    ]) assert.equal(needsBackend(g), true, `أُسقط إثباتٌ صريح: «${g}»`);
});

test('🔴 ونفيُ شيءٍ لا يُسقط إثباتَ غيرِه — بفاصلةٍ وبغير فاصلة', () => {
    // بفاصلة: صنفُ المحارف يوقف المدى من تلقائه
    assert.equal(needsBackend('متجرٌ بلا تسجيل دخول، لكنّ فيه دفعاً إلكترونيّاً'), true,
        'نفيُ كلمةٍ واحدة أسقط كلَّ ما بعدها');
    // وبغير فاصلة: لا يوقفه إلّا رابطُ الاستدراك نفسُه — وهو المقيسُ هنا
    assert.equal(needsBackend('متجرٌ بلا تسجيل دخول لكنّ فيه دفعاً إلكترونيّاً'), true,
        'ابتلع النفيُ الاستدراكَ فأسقط الدفع');
    assert.equal(needsBackend('a shop without login but with checkout'), true,
        'and the English hedge too');
});

test('🔴 والقاعدةُ العلاقيّة كذلك — «بلا postgres» لا تعني postgres', () => {
    assert.equal(needsRelationalDb('أداةٌ بسيطة بلا postgres'), false);
    assert.equal(needsRelationalDb('نظامٌ محاسبيّ على postgres'), true);
});

// ── وكلمتان مفردتان تُصيبان معنىً ليس معناهما ───────────────────────────────
// طيُّ النفي وحدَه لم يكفِ: بقي في المواصفة نفسِها «**تسجيل** ما حُفظ» و«بقاء
// **البيانات**» — وكلتاهما تصف عكسَ ما التقطه المطابِق. والقائمةُ كانت تحمل
// الصيغتَين معاً: الدقيقةَ («تسجيل دخول»، «قاعدة بيانات») والمفردةَ الأوسع.
// فأُسقطت المفردتان وبقيت الدقيقتان — الاتّساعُ وحدَه سقط لا الإشارة.
import fs from 'node:fs';

test('🔴 «تسجيل ما حُفظ» ليس تسجيلَ دخول، و«بقاء البيانات في المتصفّح» ليس قاعدةَ بيانات', () => {
    assert.equal(needsBackend('2. تسجيل ما حُفظ: أختار السورة وأضغط زرّاً'), false);
    assert.equal(needsBackend('9. بقاء البيانات: يبقى في المتصفّح فلا يضيع'), false);
});

test('🔴 والإشارةُ الدقيقة باقيةٌ كلُّها — لا ثقبَ فُتح في البوّابة', () => {
    for (const g of ['موقع فيه تسجيل دخول', 'متجر فيه قاعدة بيانات', 'صفحة تسجيل عضوية جديدة',
        'لوحة تحكم للمستخدمين', 'a site with signup', 'app with a database'])
        assert.equal(needsBackend(g), true, `أُسقطت إشارةٌ حقيقيّة: «${g}»`);
});

test('🔴 والمواصفةُ التي أشعلت هذا كلَّه لم تعد توجب خادماً', () => {
    // نصُّ صاحب المنصّة كما كُتب: «بلا خادم ولا حساب» + «تسجيل ما حُفظ» + «بقاء البيانات»
    const spec = `أريد بناء أداة «وِرد» لمتابعة حفظ القرآن الكريم، تعمل بالكامل داخل المتصفّح بلا خادم ولا حساب.

2. تسجيل ما حُفظ: أختار اسمَ السورة ورقمَ أوّل آيةٍ وآخر آية، وأضغط زرّاً.
9. بقاء البيانات: كلُّ ما أدخلتُه يبقى في المتصفّح فلا يضيع عند إغلاق الصفحة.`;
    assert.equal(needsBackend(spec), false, 'ما زالت المواصفةُ تُخرج Next.js وPrisma');
    assert.equal(needsRelationalDb(spec), false);
});
