/**
 * 🏷️ أسماء المضيفات — البدائيّتان اللتان تُبنى عليهما كل هوية نشرٍ
 *
 * اسم خدمة Render واسم مشروع Vercel كلاهما **هوية** لا تسمية: يصير الأول
 * `https://<الاسم>.onrender.com`، ويُربط الثاني بالنطاق المخصَّص للمشروع.
 * وكلاهما كان يشتقّ اسمه بصيغته الخاصة، فوقع كلاهما في العطب نفسه —
 * ولهذا صارت البدائيّتان هنا لا في أحد الملفّين.
 *
 * 🔴 **العطب المشترك: التطهير وحده يفقد ما يميّز**. اسمٌ عربي بأكمله
 * ليس فيه محرفٌ واحد من `[a-z0-9]`، فيُطهَّر إلى فراغ. والنتيجة اثنتان،
 * كلتاهما تكسر:
 *
 *   • `«متجري»` و`«دكاني»` لمستخدمٍ واحد → **الاسم نفسه** حرفياً.
 *     مشروعان يتنازعان هويةَ نشرٍ واحدة، فينشر أحدهما فوق الآخر ويشير
 *     النطاق المخصَّص لأحدهما إلى موقع الآخر.
 *   • ما يبقى ينتهي بشَرطة (`"ali-"`) — واسمٌ ينتهي بشرطة **مرفوضٌ**
 *     عند Render وVercel معاً، فالنشر يفشل قبل أن يبدأ.
 *
 * فالتطهير لا يكفي وحده: ما لا يُبقي حرفاً واحداً يُستبدَل ببصمةٍ من
 * الاسم الأصلي — قصيرةٌ وحتميّة، فالمشروع نفسه يعطي الاسم نفسه في كل
 * نشرٍ لاحق (وإلا صار لكل نشرةٍ عنوانٌ جديد)، ومشروعان مختلفان لا
 * يلتقيان.
 *
 * 📌 وليست البصمة سرّاً: SHA-1 مقتطعةٌ لغرض التمييز لا للمقاومة.
 */

import { createHash } from 'crypto';

/** جزءٌ صالحٌ في اسم مضيف: حروفٌ صغيرة وأرقامٌ وشَرَطات، بلا شَرطةٍ طرفية. */
export const slugPart = (value) =>
    String(value ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

/** بصمةٌ حتميّة قصيرة تُميّز اسماً لا يُبقي التطهيرُ منه حرفاً. */
export const nameFingerprint = (raw) =>
    'p' + createHash('sha1').update(String(raw ?? ''), 'utf8').digest('hex').slice(0, 6);

export default { slugPart, nameFingerprint };
