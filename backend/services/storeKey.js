/**
 * 🗝️ مفتاح المخزن المسطّح — انضمامُ حقلَين لا يخلطهما
 *
 * أحد عشر مخزناً ملفّياً في `services/` يشتقّ اسم ملفّه بالصياغة نفسها:
 *
 *     clean(user) + '__' + clean(project)      // + '__' + clean(slot) في ثلاثة منها
 *     clean(s) = s.replace(/[^a-zA-Z0-9_-]/g, '_')
 *
 * 🔴 **وهذه الصياغة ليست اقتراناً متبايناً.** الفاصل `__` مبنيٌّ من `_`،
 * و`_` حرفٌ **مشروع داخل الحقلين نفسيهما**: اسم المستخدم يقبله
 * (`^[a-zA-Z][a-zA-Z0-9_\-]{2,19}$`) واسم المشروع يقبله
 * (`replace(/[^a-z0-9_\-]/g, '-')`). فزوجان مختلفان يكتبان ملفاً واحداً:
 *
 *     ('alice',      'bob__site')  →  alice__bob__site.json
 *     ('alice__bob', 'site')       →  alice__bob__site.json
 *
 * وأثقلها `siteCreds`: لوحة الموقع المنشور. مَن يسجّل `alice__bob` وينشئ
 * مشروع `site` يطالب — بمشروعه هو، بلا احتيال ظاهر — بملفّ اعتماد لوحة
 * `alice/bob__site`. فتُردّ مطالبةُ صاحبها بـ«معيّنة سلفاً»، ويدخل هو
 * على لوحتها بكلمته فيأخذ توكناً موقّعاً على `{alice, bob__site}` صحيحاً
 * تماماً — يكتب محتوى موقعها ويرفع ملفّاتها. الحارس سليم، والمفتاح كذب.
 *
 * ولا يكفي منعُ `__` داخل الحقل: التباسٌ ثانٍ عند الحدود. الفاصل جارُ
 * الحقل، فـ`('a_','b')` و`('a','_b')` كلاهما `a___b`. فشرطُ الوضوح
 * ثلاثي: لا `__` داخل الحقل، ولا `_` في أوّله، ولا `_` في آخره — عندئذٍ
 * كل تعاقب `_`ين هو فاصلٌ حتماً، والقسمة وحيدة.
 *
 * 📌 ولذلك **لا يُطبَّع الالتباس بالطيّ**: جعل `__` تؤول إلى `_` يستبدل
 * تصادماً بتصادم (`alice__bob` و`alice_bob` يلتقيان). فالمفتاح الملتبس
 * يُوسَم بدل أن يُطوى: يُلحَق به مختصر SHA-256 للحقول بعينها، فيبقى
 * مبايناً ومقروءاً معاً.
 *
 * ✅ وما ليس ملتبساً لا يتغيّر حرفاً واحداً — وهذه كل الأسماء القائمة على
 * القرص عملياً: أسماء المستخدمين والمشاريع اليوم كلها ضمن أبجدية `clean`
 * (التسجيل يفرضها، وOAuth يطهّرها عند الإنشاء)، ونادرٌ فيها `_` طرفيّ.
 * أما السجلّ الملتبس — إن وُجد — فيُيتَّم عمداً: هو بالتعريف سجلٌّ لا
 * يُعرَف صاحبه، وتسليمه لأحد الطرفين أسوأ من إعادة فتحه لصاحبه الحقيقي.
 */

import crypto from 'crypto';

const SEP = '__';

/** أبجدية المفتاح — منقولة حرفياً من المخازن الأحد عشر (لا تُغيَّر). */
export const cleanSegment = (value) => String(value ?? '').replace(/[^a-zA-Z0-9_-]/g, '_');

/** هل يلتبس هذا الحقل بالفاصل؟ (فراغ، أو `_` طرفيّ، أو `__` داخلي) */
const ambiguous = (s) => s === '' || s.startsWith('_') || s.endsWith('_') || s.includes(SEP);

/**
 * يبني مفتاح مخزنٍ مسطّحاً **مبايناً**: زوجان مختلفان لا يعطيان مفتاحاً واحداً.
 * @param {...any} parts الحقول بترتيبها (مستخدم، مشروع، [شريحة]).
 * @returns {string}
 */
export function storeKey(...parts) {
    const cleaned = parts.map(cleanSegment);
    const flat = cleaned.join(SEP);
    if (!cleaned.some(ambiguous)) return flat;
    const mark = crypto.createHash('sha256').update(JSON.stringify(cleaned)).digest('hex').slice(0, 16);
    return `${flat}${SEP}x${mark}`;
}

export default { storeKey, cleanSegment };
