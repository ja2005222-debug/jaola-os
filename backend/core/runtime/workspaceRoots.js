/**
 * 🗂️ Workspace Roots — تصريحٌ واحدٌ لجذور القرص التي تكتب فيها الخلفية.
 *
 * **المقيس قبل هذا الملفّ**: ١٩٨ موضعَ كتابةٍ في ٤٦ ملفاً، تنتهي كلُّها إلى
 * ثلاثة جذور — و**الجذورُ الثلاثة كانت تُشتقّ في اثني عشر موضعاً مستقلاًّ**
 * (`workspace` ٤، `memory` ٥، `plugins` ٣)، كلٌّ بعدِّ `..` خاصٍّ به.
 *
 * وهذا وحده يمنع أيَّ بوّابةٍ مستقبليّة: لا يمكن ضبطُ ما لا مكانَ واحداً
 * يسمّيه. فليست هذه بوّابةَ كتابةٍ — بل **الشرطُ الذي بدونه لا بوّابةَ أصلاً**.
 * وهي العائلةُ نفسُها التي عولجت في Sprint 7/1 (`needsBackend` مصدراً واحداً)
 * و7/2 (اسمُ خدمة النشر بستّة اشتقاقات): سؤالٌ واحدٌ بأجوبةٍ متعدّدة.
 *
 * 🔬 **نتيجةٌ مقيسة**: الاثنا عشر كلُّها تحلّ إلى المسارات نفسها اليوم — فلا
 *    عطبَ سلوكيّاً في الجذور. الانحرافُ الوحيد المُكتشَف كان في **اشتقاق مسار
 *    المشروع** لا الجذر: `jcr.js` كان يبني `<ws>/<user>/<project>` بيده بلا
 *    الاحتياطَين (`guest_user`/`sandbox_app`) اللذين في `projectPathOf`، فلو
 *    خلا الاسمُ لاختلف المسارُ عن مسار بقيّة النظام. يُنقل إلى `projectPathOf`.
 *
 * ⚠️ **لا يُنشئ هذا الملفُّ شيئاً على القرص**. الاشتقاقُ نقيّ؛ وإنشاءُ
 *    `workspace/` يبقى في `server.js` عند الإقلاع. الخلطُ بينهما هو بعينه
 *    عطبُ `getProjectPath` القديم: فحصُ وجودٍ يُنشئ ما يفحصه فلا يقع أبداً.
 *
 * 📌 خارج النطاق عمداً: `knowledge/` (قراءةٌ فقط) و`jaola_os.db` (ملفٌّ مفرد،
 *    لا جذرَ كتابة). توسيعُ النطاق بلا حاجةٍ يُسمّي الشيءَ أوسعَ ممّا هو.
 */

import path from 'path';
import { fileURLToPath } from 'url';

/** جذر `backend/` — مشتقٌّ من موقع هذا الملفّ (`core/runtime/`). */
export const BACKEND_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** مساحةُ عمل المستخدمين — **خارج** `backend/`، في جذر المستودع. */
export const WORKSPACE_ROOT = path.resolve(BACKEND_ROOT, '../workspace');

/** ذاكرةُ المنصّة الملفّية (سجلّ المهامّ، ملفّات المستخدمين، ذاكرةُ المحادثة). */
export const MEMORY_ROOT = path.join(BACKEND_ROOT, 'memory');

/** إضافاتُ المنصّة المحمّلة من القرص. */
export const PLUGINS_ROOT = path.join(BACKEND_ROOT, 'plugins');

/** ملفٌّ داخل `memory/` — يختصر `path.join(MEMORY_ROOT, name)` عند المستدعين. */
export const memoryFile = (name) => path.join(MEMORY_ROOT, name);
