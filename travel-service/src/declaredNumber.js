/**
 * 🔢 «صرّح المزوّد» مقابل «سكت» — تمييزٌ يقرّر بيعاً
 *
 * حقولٌ رقمية كثيرة تصل من المزوّد **اختيارية**: قد تأتي برقم، وقد تغيب،
 * وقد تأتي `null` صراحةً. والفرق بين «قال صفراً» و«لم يقل شيئاً» ليس
 * تفصيلاً أسلوبياً — هو الفرق بين رفض بيعٍ وقبوله:
 *
 *   `maximum_quantity: 0`     → **لا شيء متاح**، فلا تُباع ولو واحدة.
 *   `maximum_quantity` غائب   → لم يُصرَّح، فنسقط على حدٍّ محافظ (واحدة).
 *
 * 🔴 و`Number()` وحدها **تمحو هذا التمييز في الاتجاهين معاً**:
 *
 *   `Number(null)` و`Number('')` و`Number([])` كلها **صفر** — فسكوتٌ
 *   صريح يُقرأ «صفر متاح» فيُمنع بيعٌ مشروع.
 *   و`Number(x) || 1` يقلبها: صفرٌ حقيقي يُقرأ «لم يُصرَّح» فيصير واحداً،
 *   فتُباع حقيبةٌ قال الناقل إنه لا يملكها ويُقبض ثمنها.
 *
 * وقد وقع الاتجاهان فعلاً في هذه الخدمة: الأول في استرداد المزوّد (صمتٌ
 * قُرئ صفراً فلم يُرَدَّ للمسافر شيء)، والثاني هنا في حدّ كمية الأمتعة.
 * فالقاعدة واحدة ومكتوبة مرّة: **لا يُعدّ مصرَّحاً به إلا عددٌ فعليّ أو
 * نصٌّ رقميٌّ غير فارغ** — نفس انضباط `roundMoney` في `pricing.js`.
 */

/**
 * @returns {number|null} العدد كما صرّح به المزوّد، أو `null` إن سكت.
 *   الصفر **قيمةٌ مصرَّح بها** لا غياب — وهذا كل الغرض.
 */
export function declaredNumber(value) {
    if (typeof value === 'number') return Number.isFinite(value) ? value : null;
    if (typeof value === 'string' && value.trim() !== '') {
        const n = Number(value);
        return Number.isFinite(n) ? n : null;
    }
    return null;
}

export default { declaredNumber };
